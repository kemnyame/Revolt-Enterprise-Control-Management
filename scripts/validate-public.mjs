import fs from 'node:fs';
const html=fs.readFileSync(new URL('../public/index.html',import.meta.url),'utf8');
const source=fs.readFileSync(new URL('../public/management.js',import.meta.url),'utf8');
const required=['loginView','appView','authForm','authFields','authTitle','authIntro','authSubmit','authMessage','forgotLink','backLogin','sidebar','navigation','orgName','userName','userRole','userInitial','pageTitle','content','menuBtn','refreshBtn','logoutBtn','recordDialog','dialogTitle','dialogBody','dialogClose','toast'];
for(const id of required)if(!html.includes('id="'+id+'"'))throw new Error('Missing UI container: '+id);
const ids=[...html.matchAll(/\sid="([^"]+)"/g)].map(m=>m[1]);
if(new Set(ids).size!==ids.length)throw new Error('Duplicate static DOM ids');
if(!html.includes('src="/management.js"'))throw new Error('Missing current application bundle');
if(/localStorage\.setItem|innerHTML\s*=\s*e\.message/.test(source))throw new Error('Unsafe session or error rendering');
console.log('Public browser UI validation passed');
